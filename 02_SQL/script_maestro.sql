CREATE OR REPLACE TRIGGER trg_auditoria_beneficios
AFTER INSERT OR UPDATE
ON bitacora_beneficios
FOR EACH ROW

DECLARE

    v_operacion VARCHAR2(10);

BEGIN

    IF INSERTING THEN

        v_operacion := 'INSERT';

    ELSIF UPDATING THEN

        v_operacion := 'UPDATE';

    END IF;

    INSERT INTO auditoria_beneficios (

        id_bitacora,
        operacion,
        usuario_bd,
        fecha_evento,
        categoria_anterior,
        categoria_nueva,
        total_anterior,
        total_nuevo

    )
    VALUES (

        :NEW.id_bitacora,
        v_operacion,
        USER,
        SYSDATE,
        :OLD.categoria_cliente,
        :NEW.categoria_cliente,
        :OLD.total_compras,
