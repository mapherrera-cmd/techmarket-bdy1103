-- ============================================================
-- 10. CURSORES PARAMETRIZADOS + LOOP ANIDADO
-- ============================================================

DECLARE

    v_id_sucursal NUMBER := 10;

    v_fecha_desde DATE :=
        DATE '2026-08-01';

    v_fecha_hasta DATE :=
        DATE '2026-08-31';

    -- CURSOR MAESTRO
    CURSOR cur_clientes(
        p_id_sucursal NUMBER,
        p_fecha_desde DATE,
        p_fecha_hasta DATE
    )
    IS

        SELECT DISTINCT
            c.id_cliente,
            c.nombre

        FROM cliente c

        JOIN venta v
            ON c.id_cliente = v.id_cliente

        WHERE v.id_sucursal = p_id_sucursal

        AND v.fecha_venta
            BETWEEN p_fecha_desde
            AND p_fecha_hasta

        ORDER BY c.id_cliente;

    -- CURSOR DETALLE
    CURSOR cur_ventas(
        p_id_cliente NUMBER,
        p_id_sucursal NUMBER,
        p_fecha_desde DATE,
        p_fecha_hasta DATE
    )
    IS

        SELECT
            id_venta,
            fecha_venta,
            total

        FROM venta

        WHERE id_cliente = p_id_cliente

        AND id_sucursal = p_id_sucursal

        AND fecha_venta
            BETWEEN p_fecha_desde
            AND p_fecha_hasta

        ORDER BY fecha_venta;

    v_cantidad_compras NUMBER;

    v_total_comprado NUMBER;

BEGIN

    -- LOOP MAESTRO
    FOR cliente IN cur_clientes(
        v_id_sucursal,
        v_fecha_desde,
        v_fecha_hasta
    )
    LOOP

        v_cantidad_compras := 0;

        v_total_comprado := 0;

        DBMS_OUTPUT.PUT_LINE(
            '--------------------------------'
        );

        DBMS_OUTPUT.PUT_LINE(
            'Cliente: ' ||
            cliente.id_cliente ||
            ' - ' ||
            cliente.nombre
        );

        -- LOOP DETALLE
        FOR venta IN cur_ventas(
            cliente.id_cliente,
            v_id_sucursal,
            v_fecha_desde,
            v_fecha_hasta
        )
        LOOP

            v_cantidad_compras :=
                v_cantidad_compras + 1;

            v_total_comprado :=
                v_total_comprado + venta.total;

            DBMS_OUTPUT.PUT_LINE(
                '  Venta: ' ||
                venta.id_venta ||
                ' | Fecha: ' ||
                TO_CHAR(
                    venta.fecha_venta,
                    'DD/MM/YYYY'
                ) ||
                ' | Total: $' ||
                venta.total
            );

        END LOOP;

        DBMS_OUTPUT.PUT_LINE(
            'Cantidad compras: ' ||
            v_cantidad_compras
        );

        DBMS_OUTPUT.PUT_LINE(
            'Total comprado: $' ||
            v_total_comprado
        );

        DBMS_OUTPUT.PUT_LINE(
            'Categoria: ' ||
            calcular_categoria(
                v_total_comprado
            )
        );

        DBMS_OUTPUT.PUT_LINE(
            'Beneficio: ' ||
            calcular_beneficio(
                v_total_comprado
            ) ||
            '%'
        );

    END LOOP;

END;
/

-- ============================================================
-- 11. PROCEDURE: PROCESAR_BENEFICIOS
-- ============================================================

CREATE OR REPLACE PROCEDURE procesar_beneficios(
    p_id_sucursal IN NUMBER,
    p_fecha_desde IN DATE,
    p_fecha_hasta IN DATE
)
IS

    v_total_comprado NUMBER;

    v_cantidad_compras NUMBER;

    v_categoria VARCHAR2(20);

    v_beneficio NUMBER;

BEGIN

    FOR cliente IN (

        SELECT
            c.id_cliente,
            c.nombre

        FROM cliente c

        JOIN venta v
            ON c.id_cliente = v.id_cliente

        WHERE v.id_sucursal = p_id_sucursal

        AND v.fecha_venta
            BETWEEN p_fecha_desde
            AND p_fecha_hasta

        GROUP BY
            c.id_cliente,
            c.nombre

        ORDER BY c.id_cliente

    )
    LOOP

        SELECT
            COUNT(v.id_venta),
            NVL(SUM(v.total), 0)

        INTO
            v_cantidad_compras,
            v_total_comprado

        FROM venta v

        WHERE v.id_cliente =
            cliente.id_cliente

        AND v.id_sucursal =
            p_id_sucursal

        AND v.fecha_venta
            BETWEEN p_fecha_desde
            AND p_fecha_hasta;

        v_categoria :=
            calcular_categoria(
                v_total_comprado
            );

        v_beneficio :=
            calcular_beneficio(
                v_total_comprado
            );

        INSERT INTO bitacora_beneficios (

            id_cliente,
            id_sucursal,
            periodo_desde,
            periodo_hasta,
            cantidad_compras,
            total_compras,
            categoria_cliente,
            porcentaje_beneficio,
            fecha_proceso,
            usuario_bd,
            fecha_actualizacion

        )
        VALUES (

            cliente.id_cliente,
            p_id_sucursal,
            p_fecha_desde,
            p_fecha_hasta,
            v_cantidad_compras,
            v_total_comprado,
            v_categoria,
            v_beneficio,
            SYSDATE,
            USER,
            SYSDATE

        );

        DBMS_OUTPUT.PUT_LINE(
            'Cliente: ' ||
            cliente.id_cliente ||
            ' | Compras: ' ||
            v_cantidad_compras ||
            ' | Total: $' ||
            v_total_comprado ||
            ' | Categoria: ' ||
            v_categoria ||
            ' | Beneficio: ' ||
            v_beneficio ||
            '%'
        );

    END LOOP;

END procesar_beneficios;
