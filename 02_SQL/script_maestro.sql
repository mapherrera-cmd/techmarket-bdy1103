-- ============================================================
-- 17. P4 - SUCURSAL SIN VENTAS
-- EXCEPCION DEFINIDA POR EL USUARIO
-- ============================================================

DECLARE

    v_sucursal_id NUMBER := 20;

    v_fecha_inicio DATE :=
        DATE '2026-09-01';

    v_fecha_fin DATE :=
        DATE '2026-09-30';

    v_total_ventas NUMBER;

    ex_sin_ventas EXCEPTION;

BEGIN

    SELECT COUNT(*)

    INTO v_total_ventas

    FROM venta

    WHERE id_sucursal = v_sucursal_id

    AND fecha_venta
        BETWEEN v_fecha_inicio
        AND v_fecha_fin;

    IF v_total_ventas = 0 THEN

        RAISE ex_sin_ventas;

    END IF;

    DBMS_OUTPUT.PUT_LINE(
        'La sucursal tiene ventas en el periodo.'
    );

EXCEPTION

    WHEN ex_sin_ventas THEN

        DBMS_OUTPUT.PUT_LINE(
            'ERROR: La sucursal ' ||
            v_sucursal_id ||
            ' no registro ventas en el periodo.'
        );

    WHEN OTHERS THEN

        DBMS_OUTPUT.PUT_LINE(
            'ERROR NO ESPERADO: ' ||
            SQLERRM
        );

END;
