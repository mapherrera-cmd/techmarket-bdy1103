CREATE TABLE sucursal (
    id_sucursal NUMBER(4)
        CONSTRAINT pk_sucursal PRIMARY KEY,
    nombre VARCHAR2(80) NOT NULL,
    comuna VARCHAR2(80) NOT NULL
);

CREATE TABLE cliente (
    id_cliente NUMBER(6)
        CONSTRAINT pk_cliente PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    correo VARCHAR2(150)
        CONSTRAINT uq_cliente_correo UNIQUE,
    estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
    fecha_registro DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT ck_cliente_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE producto (
    id_producto NUMBER(6)
        CONSTRAINT pk_producto PRIMARY KEY,
    nombre_producto VARCHAR2(120) NOT NULL,
    categoria VARCHAR2(60) NOT NULL,
    precio NUMBER(12,2) NOT NULL,
    stock NUMBER(8) DEFAULT 0 NOT NULL,

    CONSTRAINT ck_producto_precio
        CHECK (precio > 0),

    CONSTRAINT ck_producto_stock
        CHECK (stock >= 0)
);

CREATE TABLE venta (
    id_venta NUMBER(8)
        CONSTRAINT pk_venta PRIMARY KEY,
    id_sucursal NUMBER(4) NOT NULL,
    id_cliente NUMBER(6) NOT NULL,
    fecha_venta DATE NOT NULL,
    total NUMBER(14,2) NOT NULL,

    CONSTRAINT fk_venta_sucursal
        FOREIGN KEY (id_sucursal)
        REFERENCES sucursal(id_sucursal),

    CONSTRAINT fk_venta_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente(id_cliente),

    CONSTRAINT ck_venta_total
        CHECK (total >= 0)
);

CREATE TABLE detalle_venta (
    id_detalle NUMBER(10)
        CONSTRAINT pk_detalle_venta PRIMARY KEY,
    id_venta NUMBER(8) NOT NULL,
    id_producto NUMBER(6) NOT NULL,
    cantidad NUMBER(6) NOT NULL,
    precio_unitario NUMBER(12,2) NOT NULL,

    CONSTRAINT fk_detalle_venta
        FOREIGN KEY (id_venta)
        REFERENCES venta(id_venta),

    CONSTRAINT fk_detalle_producto
        FOREIGN KEY (id_producto)
        REFERENCES producto(id_producto),

    CONSTRAINT ck_detalle_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_detalle_precio
        CHECK (precio_unitario > 0)
);

CREATE TABLE bitacora_beneficios (
    id_bitacora NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_bitacora_beneficios PRIMARY KEY,

    id_cliente NUMBER(6) NOT NULL,
    id_sucursal NUMBER(4) NOT NULL,
    periodo_desde DATE NOT NULL,
    periodo_hasta DATE NOT NULL,
    cantidad_compras NUMBER(6) NOT NULL,
    total_compras NUMBER(14,2) NOT NULL,
    categoria_cliente VARCHAR2(20) NOT NULL,
    porcentaje_beneficio NUMBER(5,2) NOT NULL,
    fecha_proceso DATE DEFAULT SYSDATE NOT NULL,
    usuario_bd VARCHAR2(128),
    fecha_actualizacion DATE,

    CONSTRAINT fk_bitacora_cliente
        FOREIGN KEY (id_cliente)
